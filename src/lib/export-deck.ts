import { type Deck, TEMPLATES, type TemplateName } from "./deck-types";

function esc(s: string) {
  return (s || "").replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!,
  );
}

/** Print-to-PDF export: opens a print-ready window with one page per slide. */
export function exportPdf(deck: Deck) {
  const tpl = TEMPLATES[(deck.template as TemplateName) in TEMPLATES ? deck.template : "Modern"];
  const w = window.open("", "_blank");
  if (!w) throw new Error("Your browser blocked the export window — allow pop-ups and try again.");
  w.document.write(`<html><head><title>${esc(deck.title)}</title><style>
    body{font-family:'${deck.font}',sans-serif;margin:0;}
    .pg{page-break-after:always;padding:60px;height:100vh;box-sizing:border-box;color:#fff;background:linear-gradient(135deg,${tpl.a},${tpl.b});}
    .pg:last-child{page-break-after:auto;}
    h2{font-size:34px;margin:0 0 18px;} ul{font-size:18px;line-height:1.7;}
    img{max-width:100%;max-height:300px;margin-top:16px;border-radius:10px;}
  </style></head><body>
  ${deck.slides
    .map(
      (s) =>
        `<div class="pg"><h2>${esc(s.title)}</h2><ul>${s.bullets
          .map((b) => `<li>${esc(b)}</li>`)
          .join("")}</ul>${s.image ? `<img src="${s.image}"/>` : ""}</div>`,
    )
    .join("")}
  </body></html>`);
  w.document.close();
  setTimeout(() => w.print(), 400);
}

